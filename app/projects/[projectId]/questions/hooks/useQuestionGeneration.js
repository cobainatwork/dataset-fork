'use client';

import { useState } from 'react';
import { useTranslation } from 'react-i18next';
import { toast } from 'sonner';
import axios from 'axios';
import i18n from '@/lib/i18n';
import request from '@/lib/util/request';
import { processInParallel } from '@/lib/util/processInParallel';

export function useQuestionGeneration(projectId, model, taskSettings, getQuestionList) {
  const { t } = useTranslation();

  // 處理狀態
  const [processing, setProcessing] = useState(false);

  // 進度狀態
  const [progress, setProgress] = useState({
    total: 0, // 總共選擇的問題數量
    completed: 0, // 已處理完成的數量
    percentage: 0, // 進度百分比
    datasetCount: 0 // 已生成的資料集數量
  });

  // 批次生成答案
  const handleBatchGenerateAnswers = async selectedQuestions => {
    if (selectedQuestions.length === 0) {
      toast.warning(t('questions.noQuestionsSelected'));
      return;
    }

    if (!model) {
      toast.warning(t('models.configNotFound'));
      return;
    }

    try {
      setProgress({
        total: selectedQuestions.length,
        completed: 0,
        percentage: 0,
        datasetCount: 0
      });

      // 然後設定處理狀態為真，確保進度條顯示
      setProcessing(true);

      toast.info(t('questions.batchGenerateStart', { count: selectedQuestions.length }));

      // 單個問題處理函式
      const processQuestion = async questionId => {
        try {
          console.log('開始生成資料集:', { questionId });
          const language = i18n.language;
          // 呼叫API生成資料集
          const response = await request(`/api/projects/${projectId}/datasets`, {
            method: 'POST',
            headers: {
              'Content-Type': 'application/json'
            },
            body: JSON.stringify({
              questionId,
              model,
              language
            })
          });

          if (!response.ok) {
            const errorData = await response.json();
            console.error(t('datasets.generateError'), errorData.error || t('datasets.generateFailed'));

            // 更新進度狀態（即使失敗也計入已處理）
            setProgress(prev => {
              const completed = prev.completed + 1;
              const percentage = Math.round((completed / prev.total) * 100);

              return {
                ...prev,
                completed,
                percentage
              };
            });

            return { success: false, questionId, error: errorData.error || t('datasets.generateFailed') };
          }

          const data = await response.json();

          // 更新進度狀態
          setProgress(prev => {
            const completed = prev.completed + 1;
            const percentage = Math.round((completed / prev.total) * 100);
            const datasetCount = prev.datasetCount + 1;

            return {
              ...prev,
              completed,
              percentage,
              datasetCount
            };
          });

          console.log(`資料集生成成功: ${questionId}`);
          return { success: true, questionId, data: data.dataset };
        } catch (error) {
          console.error('生成資料集失敗:', error);

          // 更新進度狀態（即使失敗也計入已處理）
          setProgress(prev => {
            const completed = prev.completed + 1;
            const percentage = Math.round((completed / prev.total) * 100);

            return {
              ...prev,
              completed,
              percentage
            };
          });

          return { success: false, questionId, error: error.message };
        }
      };

      // 並行處理所有問題，最多同時處理2個
      const results = await processInParallel(selectedQuestions, processQuestion, taskSettings.concurrencyLimit);

      // 重新整理資料
      getQuestionList();

      // 處理完成後設定結果訊息
      const successCount = results.filter(r => r.success).length;
      const failCount = results.filter(r => !r.success).length;

      if (failCount > 0) {
        toast.warning(
          t('datasets.partialSuccess', {
            successCount,
            total: selectedQuestions.length,
            failCount
          })
        );
      } else {
        toast.success(t('common.success', { successCount }));
      }
    } catch (error) {
      console.error('生成資料集出錯:', error);
      toast.error(error.message || '生成資料集失敗');
    } finally {
      // 延遲關閉處理狀態，確保使用者可以看到完成的進度
      setTimeout(() => {
        setProcessing(false);
        // 再次延遲重置進度狀態
        setTimeout(() => {
          setProgress({
            total: 0,
            completed: 0,
            percentage: 0,
            datasetCount: 0
          });
        }, 500);
      }, 2000); // 延遲關閉處理狀態，讓使用者看到完成的進度
    }
  };

  // 自動生成資料集
  const handleAutoGenerateDatasets = async () => {
    try {
      if (!model) {
        toast.error(t('questions.selectModelFirst', { defaultValue: '請先選擇模型' }));
        return;
      }

      // 呼叫建立任務介面
      const response = await axios.post(`/api/projects/${projectId}/tasks`, {
        taskType: 'answer-generation',
        modelInfo: model,
        language: i18n.language
      });

      if (response.data?.code === 0) {
        toast.success(t('tasks.createSuccess', { defaultValue: '後臺任務已建立，系統將自動處理未生成答案的問題' }));
      } else {
        toast.error(t('tasks.createFailed', { defaultValue: '建立後臺任務失敗' }));
      }
    } catch (error) {
      console.error('建立任務失敗:', error);
      toast.error(t('tasks.createFailed', { defaultValue: '建立任務失敗' }) + ': ' + error.message);
    }
  };

  // 自動生成影像問答資料集
  const handleAutoGenerateImageDatasets = async () => {
    try {
      if (!model) {
        toast.error(t('questions.selectModelFirst', { defaultValue: '請先選擇模型' }));
        return;
      }

      if (model.type !== 'vision') {
        toast.error(t('images.visionModelRequired', { defaultValue: '請選擇支援視覺的模型' }));
        return;
      }

      // 呼叫建立任務介面
      const response = await axios.post(`/api/projects/${projectId}/tasks`, {
        taskType: 'image-dataset-generation',
        modelInfo: model,
        language: i18n.language
      });

      if (response.data?.code === 0) {
        toast.success(t('tasks.createSuccess', { defaultValue: '後臺任務已建立，系統將自動處理未生成答案的圖片問題' }));
      } else {
        toast.error(t('tasks.createFailed', { defaultValue: '建立後臺任務失敗' }));
      }
    } catch (error) {
      console.error('建立圖片資料集任務失敗:', error);
      toast.error(t('tasks.createFailed', { defaultValue: '建立任務失敗' }) + ': ' + error.message);
    }
  };

  // 自動生成多輪對話資料集
  const handleAutoGenerateMultiTurnDatasets = async () => {
    try {
      if (!model) {
        toast.error(t('questions.selectModelFirst', { defaultValue: '請先選擇模型' }));
        return;
      }

      // 首先檢查專案是否配置了多輪對話設定
      const configResponse = await axios.get(`/api/projects/${projectId}/tasks`);
      if (configResponse.status !== 200) {
        throw new Error('獲取專案配置失敗');
      }

      const config = configResponse.data;
      const multiTurnConfig = {
        systemPrompt: config.multiTurnSystemPrompt,
        scenario: config.multiTurnScenario,
        rounds: config.multiTurnRounds,
        roleA: config.multiTurnRoleA,
        roleB: config.multiTurnRoleB
      };

      // 檢查是否已配置必要的多輪對話設定
      if (
        !multiTurnConfig.scenario ||
        !multiTurnConfig.roleA ||
        !multiTurnConfig.roleB ||
        !multiTurnConfig.rounds ||
        multiTurnConfig.rounds < 1
      ) {
        toast.error(t('questions.multiTurnNotConfigured', '請先在專案設定中配置多輪對話相關引數'));
        return;
      }

      // 呼叫建立任務介面
      const response = await axios.post(`/api/projects/${projectId}/tasks`, {
        taskType: 'multi-turn-generation',
        modelInfo: model,
        language: i18n.language,
        config: JSON.stringify(multiTurnConfig)
      });

      if (response.data?.code === 0) {
        toast.success(
          t('tasks.multiTurnCreateSuccess', {
            defaultValue: '多輪對話生成任務已建立，系統將自動處理未生成多輪對話的問題'
          })
        );
      } else {
        toast.error(t('tasks.createFailed', { defaultValue: '建立後臺任務失敗' }));
      }
    } catch (error) {
      console.error('建立多輪對話任務失敗:', error);
      toast.error(t('tasks.createFailed', { defaultValue: '建立任務失敗' }) + ': ' + error.message);
    }
  };

  return {
    // 狀態
    processing,
    progress,

    // 方法
    handleBatchGenerateAnswers,
    handleAutoGenerateDatasets,
    handleAutoGenerateMultiTurnDatasets,
    handleAutoGenerateImageDatasets
  };
}
